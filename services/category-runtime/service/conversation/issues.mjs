export const behaviourVersion = "mvp-feedback/20261023-v7";
// Reported issues are dialogue state, never category context or legal findings.
export const unknownMessage =
  "Извините, пока не удалось подобрать проверенный ответ для этой ситуации. Возможно, мы ещё не разобрали её или не совсем поняли описание. Вы можете отправить ситуацию нашей команде — мы рассмотрим её и используем, чтобы улучшить АЙзащиту. Или продолжите разговор о другой проблеме.";
export function reportedIssue(text) {
  const t = text.toLowerCase().replaceAll("ё", "е");
  if (
    /^(?:а )?если |в фильме|в кино|не (?:кричит|орет|оскорбляет|угрожает)|не (?:требуют|просит|просят).{0,15}телефон/.test(
      t,
    )
  )
    return null;
  if (/на (?:прохожего|соседа|другого человека)|у (?:прохожего|соседа)/.test(t))
    return null;
  if (
    /(?:требу[ею]т|прос[яи]т|отда[йт]|дай).{0,35}телефон|телефон.{0,25}(?:требу[ею]т|прос[яи]т)/.test(
      t,
    )
  )
    return {
      kind: "phone_demand",
      summary: "Вы сообщили, что сотрудник требует телефон.",
    };
  if (
    /угрож|пригроз|грозит|угро\s+арест|сказал.{0,25}(?:ударит|изобьет|арестует)/.test(
      t,
    )
  )
    return {
      kind: "threat",
      summary: "Вы сообщили об угрозе со стороны сотрудника.",
    };
  if (/крич|орет|повышает голос|оскорбля/.test(t))
    return {
      kind: "verbal_pressure",
      summary: "Вы сообщили, что сотрудник кричит или оскорбляет вас.",
    };
  return null;
}
