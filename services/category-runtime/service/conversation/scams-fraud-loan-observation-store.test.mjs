import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import {randomUUID} from "node:crypto";
import {createConversationService} from "./service.mjs";
const receipt="2026-10-31T10:00:00.000Z";
const message=`Я получил деньги по займу L1 на счет A1 в ${receipt}.\nЯ уже проверил выписку по счету A1 по займу L1 за весь период с ${receipt} по сейчас.\nЗа весь этот период я не снимал, не переводил, не тратил и не возвращал деньги этого займа.`;
test("real service persists observation, supports replay/resume, isolates owner and removes on delete",async t=>{
 const dataDir=await fs.mkdtemp(path.join(os.tmpdir(),"scams-g05-"));
 t.after(()=>fs.rm(dataDir,{recursive:true,force:true}));
 let now="2026-11-01T10:00:00.000Z";
 const service=()=>createConversationService({dataDir,loanObservationNow:()=>now,getActive:()=>{throw Error("Should not load active article/category");},getBundle:()=>{throw Error("No source rewrite");}});
 let app=service();
 const input={id:randomUUID(),userId:"81",categoryId:"scams_fraud",observationAction:"record",expectedRevision:0,turnId:randomUUID(),question:message,loanId:"L1",accountId:"A1"};
 const r=await app.internal(input,"loan_observation");
 assert.equal(r.values.loan_receipt_period_fully_observed,true);
 assert.equal(r.qualifiedVariantActivation,false);
 assert.deepEqual(await app.internal(input,"loan_observation"),r);
 app=service();
 const resumed=await app.internal({...input,observationAction:"read"},"loan_observation");
 assert.equal(resumed.values.received_loan_funds_not_moved,true);
 now="2026-11-01T10:00:01.000Z";
 const stale=await app.internal({...input,observationAction:"read"},"loan_observation");
 assert.equal(stale.values.loan_receipt_period_fully_observed,null);
 const foreign=await app.internal({...input,userId:"82",observationAction:"read"},"loan_observation");
 assert.equal(foreign.values.loan_money_received_by_user,null);
 await assert.rejects(app.internal({...input,turnId:randomUUID()},"loan_observation"),/STALE/);
 await assert.rejects(app.internal({...input,question:"Да"},"loan_observation"),/CONFLICT/);
 const corrected=await app.internal({...input,expectedRevision:1,turnId:randomUUID(),question:"Не знаю, проверен ли весь период"},"loan_observation");
 assert.equal(corrected.revision,2);assert.equal(corrected.values.received_loan_funds_not_moved,null);
 await app.internal(input,"delete");
 const cleared=await app.internal({...input,observationAction:"read"},"loan_observation");
 assert.equal(cleared.revision,0);assert.equal(cleared.values.loan_money_received_by_user,null);
 await assert.rejects(app.internal(input,"loan_observation"),/DELETED_LOAN_OBSERVATION/);
});
